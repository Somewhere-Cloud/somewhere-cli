#!/usr/bin/env node
import { publicProjection, assertBehaviorParity } from './public-projection.mjs';
// Regenerate (or prove byte parity with) the platform's parser and generator.
import { createHash } from 'node:crypto';
import { readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join, relative, resolve } from 'node:path';
import { platformCommit, writePlatformSource } from './platform-source.mjs';

const [sourceRoot, mode] = process.argv.slice(2);
if (!sourceRoot || (mode && mode !== '--check')) {
  throw new Error('Usage: node scripts/vendor-declared-data.mjs <platform-source> [--check]');
}
// Real path: esbuild reports its inputs relative to the resolved root (macOS /tmp).
const root = realpathSync(resolve(sourceRoot));
const compile = join(root, 'worker/containers/compile');
const require = createRequire(join(compile, 'package.json'));
const esbuild = require('esbuild');
const pinned = JSON.parse(readFileSync(join(compile, 'package.json'), 'utf8')).dependencies.esbuild;
if (esbuild.version !== pinned) throw new Error(`Install the platform compiler's pinned esbuild ${pinned} first.`);
const result = await esbuild.build({
  absWorkingDir: root,
  stdin: {
    contents: `import { clientAuthorityFromSource, declaredFilesFromSource, declaredRolesFromSource, schemaAuthorityFromSource } from './worker/src/utils/db-schema-deploy/client-contract-source.ts';
import { describeDataClientLocalDeclaration } from './worker/containers/compile/declared-data-contract.cjs';
import { generateDataClient } from './worker/containers/compile/typed-data.cjs';
import { declaredTablesDeclaration, runtimeContextDeclaration } from './worker/containers/compile/runtime-types.cjs';
import { declaredRoles } from './worker/containers/compile/groups-types.cjs';
import { describeFilesClient } from './worker/containers/compile/typed-files.cjs';
export { SCHEMA_DECLARATION } from './worker/containers/compile/schema-types.cjs';
export { ENDPOINT_DECLARATION, RUNTIME_CONTEXT_DECLARATION } from './worker/containers/compile/runtime-types.cjs';
export { CLIENT_FILE as FILES_DECLARATION_FILE } from './worker/containers/compile/typed-files.cjs';
export * as checkerContract from './worker/containers/compile/checker-contract.cjs';
export { referenceCheckDeclarations, isRuntimeEndpointGlobal } from './worker/src/utils/reference-check-inputs.ts';
export { CONSUMER_CONTRACT, consumerContractComponents, consumerContractFingerprint, consumerContractVerdict, parseConsumerContractHeader } from './worker/containers/compile/consumer-contract.cjs';
export function generateFromFiles(files) {
  const authority = clientAuthorityFromSource(files);
  return authority ? generateDataClient(authority) : undefined;
}
export function localDeclarationFromFiles(files) {
  const authority = clientAuthorityFromSource(files);
  return authority ? describeDataClientLocalDeclaration(authority) : undefined;
}
export function runtimeDeclarationFromFiles(files) {
  return runtimeContextDeclaration(declaredRoles(declaredRolesFromSource(files)));
}
export function declaredTablesFromFiles(files) {
  return declaredTablesDeclaration(schemaAuthorityFromSource(files));
}
export function filesDeclarationFromFiles(files) {
  const canonical = declaredFilesFromSource(files);
  return canonical ? describeFilesClient(canonical).declaration : undefined;
}`,
    resolveDir: root, sourcefile: 'declared-data-vendor-entry.js', loader: 'js',
  },
  bundle: true, platform: 'node', target: 'node22', format: 'cjs', write: false,
  // Paths in the bundle stay under the platform root wherever node_modules is linked from.
  metafile: true, legalComments: 'none', preserveSymlinks: true,
});
assertBehaviorParity(result.outputFiles[0].text, publicProjection(result.outputFiles[0].text, 'vendor.js'), 'vendor.js');
if (mode === '--check') assertBehaviorParity(result.outputFiles[0].text, readFileSync(join(import.meta.dirname, '../runtime/declared-data.cjs'), 'utf8'), 'vendor.js');
const output = '// Generated by scripts/vendor-declared-data.mjs; edit the platform source.\n' + publicProjection(result.outputFiles[0].text, 'vendor.js');
const digest = text => createHash('sha256').update(text).digest('hex');
const inputs = Object.fromEntries(Object.keys(result.metafile.inputs)
  .filter(path => path !== 'declared-data-vendor-entry.js')
  .sort().map(path => [relative(root, resolve(root, path)), digest(readFileSync(resolve(root, path)))]));
const manifest = JSON.stringify({ esbuild: esbuild.version, source_files: inputs, sha256: digest(output) }, null, 2) + '\n';
const dest = join(import.meta.dirname, '..', 'runtime');

for (const [name, content] of [['declared-data.cjs', output], ['DECLARED-DATA-VENDOR.json', manifest]]) {
  if (mode === '--check') {
    if (readFileSync(join(dest, name), 'utf8') !== content) throw new Error(`${name} differs from the platform source; regenerate it.`);
  } else writeFileSync(join(dest, name), content);
}
console.log(`Declared data ${mode === '--check' ? 'parity verified' : 'vendored'}: ${digest(output)}`);

if (mode !== '--check') { platformCommit(root, Object.keys(inputs)); writePlatformSource(join(import.meta.dirname, '..')); }
