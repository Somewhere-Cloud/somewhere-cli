// Same vendored-source pattern as vendor-declared-data: no second rule engine.
import { createHash } from 'node:crypto';
import { readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { join, relative, resolve } from 'node:path';
const [sourceRoot, mode] = process.argv.slice(2);
if (!sourceRoot || (mode && mode !== '--check')) throw new Error('Usage: node scripts/vendor-source-lint.mjs <platform-source> [--check]');
const root = realpathSync(resolve(sourceRoot));
const require = createRequire(join(root, 'worker/package.json'));
const esbuild = require('esbuild');
const pinned = JSON.parse(readFileSync(join(root, 'worker/package.json'), 'utf8')).devDependencies.esbuild.replace(/^\^/, '');
if (esbuild.version !== pinned) throw new Error(`Install the platform's esbuild ${pinned} first.`);
const result = await esbuild.build({
  absWorkingDir: root, entryPoints: ['worker/src/services/source-lint.ts'],
  bundle: true, platform: 'neutral', target: 'es2022', format: 'cjs', write: false,
  metafile: true, legalComments: 'none',
});
const output = '// Generated by scripts/vendor-source-lint.mjs; edit platform source.\n' + result.outputFiles[0].text;
const digest = data => createHash('sha256').update(data).digest('hex');
const inputs = Object.fromEntries(Object.keys(result.metafile.inputs).sort().map(path => [relative(root, resolve(root, path)), digest(readFileSync(resolve(root, path)))]));
const fixtures = readFileSync(join(root, 'worker/verify/fixtures/source-lint.json'), 'utf8');
const manifest = JSON.stringify({ esbuild: esbuild.version, source_files: inputs, sha256: digest(output), fixtures_sha256: digest(fixtures) }, null, 2) + '\n';
for (const [name, contents] of [['runtime/source-lint.cjs', output], ['runtime/SOURCE-LINT-VENDOR.json', manifest], ['test/fixtures/source-lint.json', fixtures]]) {
  const path = join(import.meta.dirname, '..', name);
  if (mode === '--check') {
    if (readFileSync(path, 'utf8') !== contents) throw new Error(`${name} differs from platform source.`);
  } else writeFileSync(path, contents);
}
console.log(`Source lint ${mode === '--check' ? 'parity verified' : 'vendored'}: ${digest(output)} (${Buffer.byteLength(output)} bytes)`);
